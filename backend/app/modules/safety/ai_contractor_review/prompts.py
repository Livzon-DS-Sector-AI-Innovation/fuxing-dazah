# ═══════════════════════════════════════════════════════════════
# User prompt 构造（动态数据放尾部）
# ═══════════════════════════════════════════════════════════════


def build_user_prompt(input_data: AdmissionReviewInput) -> str:
    """构建 user 消息：固定指令在前，变量数据（协议文本/视觉描述/RAG）在后。"""
    parts: list[str] = [
        "请对以下承包商安全管理协议进行审核，严格按 JSON 输出 "
        '{"agreement": {"conclusion": ..., "report": ..., "defects": [...]}, '
        '"overall_conclusion": "...", "overall_report": "...", '
        '"defect_categories": ["..."]}：',
        "",
        f"作业单位名称：{input_data.company_name or '-'}",
        f"相关方类型：{input_data.related_party_type or '-'}",
        "",
        "【安全管理协议文本提取】",
        input_data.agreement_text or "（未提取到文本）",
        "",
        "【安全管理协议视觉描述（公章/签字/骑缝章）】",
        input_data.agreement_vision_desc or "（无视觉信息/未发现）",
        "",
    ]
    if input_data.knowledge_md:
        parts += ["【参考法规】", input_data.knowledge_md, ""]
    return "\n".join(parts)
